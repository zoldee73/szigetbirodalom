import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
let source=fs.readFileSync(new URL('./server.js',import.meta.url),'utf8');
source=source.slice(source.indexOf('const rooms='),source.indexOf("wss.on('connection'"));
const ctx=vm.createContext({randomBytes:()=>Buffer.alloc(3),Buffer,Math,Date,console,Map,Set});
vm.runInContext(source+';globalThis.testing={newRoom,legalRoad,legalVillage,roadLength,tradeRatio,action};',ctx);
const {newRoom,legalRoad,legalVillage,action}=ctx.testing;
const s=newRoom('classic2');
assert.equal(s.tiles.length,19);assert.equal(s.vertices.length,54);assert.equal(s.edges.length,72);
assert.equal(s.capacity,2);assert.equal(s.bank.wood,19);
const p={id:0,name:'A',resources:{wood:5,brick:5,wheat:5,sheep:5,ore:5},dev:[],knights:0,turnSerial:0,devPlayed:false};
const q={...p,id:1,name:'B',resources:{...p.resources}};s.players=[p,q];
const room={state:s};
assert.equal(action(room,p,{action:'start'}),undefined);
assert.equal(s.phase,'setup');
const v=s.vertices.find(v=>legalVillage(s,v,p,true)).id;
assert.equal(action(room,p,{action:'village',id:v}),undefined);
const e=s.edges.find(e=>e.a===v||e.b===v).id;
assert.equal(legalRoad(s,e,p,true),true);
assert.equal(action(room,p,{action:'road',id:e}),undefined);
assert.equal(s.setupIndex,1);
assert.equal(s.roads[e],0);
assert.equal(legalRoad(s,e,p,true),false);
console.log('PASS: map 19/54/72, bank, 2-player lobby, initial settlement and road, occupied road rejection');
const duo=newRoom('duo');assert.equal(duo.capacity,2);
assert.equal(duo.ports.length,9);
assert.ok(duo.ports.every(port=>port.vertices.length===2&&port.vertices.every(v=>Number.isInteger(v)&&v>=0&&v<54)));
const classic=newRoom('classic');classic.players=[p,{...p,id:1},{...p,id:2}];
assert.equal(classic.capacity,4);
console.log('PASS: harbor endpoints, mode capacities');
